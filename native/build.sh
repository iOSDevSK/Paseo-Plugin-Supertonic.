#!/bin/sh
# Builds the universal apple-stt helper and embeds it in server/apple-stt-binary.ts.
set -e
cd "$(dirname "$0")"
swiftc -O -target arm64-apple-macos26 AppleSTT.swift -o /tmp/apple-stt-arm64
swiftc -O -target x86_64-apple-macos26 AppleSTT.swift -o /tmp/apple-stt-x86_64
lipo -create /tmp/apple-stt-arm64 /tmp/apple-stt-x86_64 -output /tmp/apple-stt
codesign --force --sign - /tmp/apple-stt
{
  echo "// Generated by native/build.sh from native/AppleSTT.swift. Do not edit."
  printf 'export const APPLE_STT_BINARY_BASE64 =\n  "%s";\n' "$(base64 -i /tmp/apple-stt | tr -d '\n')"
} > ../server/apple-stt-binary.ts
ls -l /tmp/apple-stt ../server/apple-stt-binary.ts
